    <h2>1. Présentation du service</h2>
    <p>
      Loomkeep est un service de suivi et de gestion personnelle de contenus
      culturels.
    </p>
    <p>
      Le service permet notamment de rechercher, organiser et suivre différents
      types de contenus, tels que :
    </p>
    <ul>
      <li>films ;</li>
      <li>séries ;</li>
      <li>anime ;</li>
      <li>livres ;</li>
      <li>jeux vidéo ;</li>
      <li>musique ;</li>
      <li>
        et, selon les fonctionnalités disponibles, d'autres catégories de
        contenus culturels.
      </li>
    </ul>
    <p>
      Loomkeep peut également proposer des fonctionnalités sociales permettant
      notamment de suivre d'autres utilisateurs, publier des avis ou
      commentaires, créer des listes et partager certaines informations selon
      les paramètres de confidentialité choisis.
    </p>
    <p>
      Loomkeep ne fournit pas nécessairement les contenus eux-mêmes. Les
      informations relatives aux œuvres sont notamment obtenues auprès de
      services et bases de données tiers.
    </p>
