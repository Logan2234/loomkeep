    <h2>12. Suppression du compte</h2>
    <p>
      L'utilisateur peut supprimer son compte selon les fonctionnalités
      proposées par Loomkeep.
    </p>
    <p>
      La suppression entraîne la suppression des données personnelles dans les
      systèmes actifs, sous réserve notamment :
    </p>
    <ul>
      <li>
        des données devant être conservées en application d'une obligation
        légale ;
      </li>
      <li>
        des informations nécessaires à la prévention des abus ou à la défense
        des droits ;
      </li>
      <li>
        des données techniques présentes temporairement dans les sauvegardes.
      </li>
    </ul>
    <p>
      Les sauvegardes sont soumises à leur propre cycle de rétention et ne sont
      pas utilisées pour restaurer volontairement les données d'un compte
      supprimé.
    </p>
    <p>
      Certains contenus sociaux peuvent être supprimés ou anonymisés lorsqu'une
      suppression complète est incompatible avec le fonctionnement technique du
      service ou avec les obligations applicables.
    </p>
    <h2>13. Sécurité</h2>
    <p>
      Loomkeep met en œuvre des mesures techniques et organisationnelles
      destinées à protéger les données personnelles contre les accès non
      autorisés, la perte, la destruction, l'altération ou la divulgation.
    </p>
    <p>Ces mesures peuvent notamment comprendre :</p>
    <ul>
      <li>chiffrement des communications ;</li>
      <li>stockage sécurisé des mots de passe ;</li>
      <li>mécanismes de gestion de session ;</li>
      <li>contrôle des accès ;</li>
      <li>mesures de protection contre les accès abusifs ;</li>
      <li>sauvegardes ;</li>
      <li>journalisation des événements de sécurité ;</li>
      <li>mises à jour de sécurité.</li>
    </ul>
    <p>
