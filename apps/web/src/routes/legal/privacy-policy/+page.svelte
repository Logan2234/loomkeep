    <h2>7. Notifications push</h2>
    <p>
      Lorsque l'utilisateur active les notifications push, Loomkeep traite les
      informations techniques nécessaires à l'envoi des notifications vers son
      appareil ou navigateur.
    </p>
    <p>
      Techniquement, cet envoi transite par le service de notification propre au
      navigateur ou à l'appareil de l'utilisateur — notamment Firebase Cloud
      Messaging (Google) pour Chrome et la plupart des navigateurs Android, le
      service Push de Mozilla pour Firefox, ou le service de notifications
      d'Apple pour Safari/iOS — qui reçoit à cette fin l'adresse technique de
      l'abonnement (endpoint). Le contenu de la notification est chiffré de bout
      en bout : ce service ne peut pas le lire en clair.
    </p>
    <p>
      L'utilisateur peut désactiver ces notifications depuis Loomkeep ou depuis
      les paramètres de son appareil ou navigateur, selon le mécanisme utilisé.
    </p>
    <p>
      Les abonnements push devenus inutiles ou invalides peuvent être supprimés.
    </p>
    <h2>8. Newsletter</h2>
    <p>L'inscription à la newsletter est facultative.</p>
    <p>
      Lorsque le consentement est requis, la newsletter n'est envoyée qu'après
      obtention de ce consentement.
    </p>
    <p>
      L'utilisateur peut retirer son consentement à tout moment, notamment au
      moyen du lien de désinscription présent dans les e-mails concernés.
    </p>
    <p>
      Le retrait du consentement n'affecte pas la licéité des traitements
      effectués avant ce retrait.
    </p>
    <h2>9. Cookies et stockage local</h2>
    <p>
      Loomkeep peut utiliser des mécanismes de stockage côté navigateur,
      notamment pour assurer certaines fonctions nécessaires au fonctionnement
      du service, telles que l'authentification, les préférences ou l'état de
      l'application.
    </p>
    <p>
      Les mécanismes strictement nécessaires au fonctionnement du service ne
      sont pas utilisés à des fins de publicité comportementale.
    </p>
    <p>Concrètement, Loomkeep utilise :</p>
    <ul>
      <li>
        un cookie <code>PARAGLIDE_LOCALE</code> (durée de vie : 400 jours), pour mémoriser
        la langue choisie ;
      </li>
      <li>
        un stockage local (<code>localStorage</code>) contenant les jetons de
        connexion, le thème choisi (clair/sombre) et l'état replié/déplié de la
        barre latérale.
      </li>
    </ul>
    <p>Aucun de ces éléments n'est utilisé à des fins de suivi publicitaire.</p>
    <p>
      La mesure d'audience de la page d'accueil (voir section 6, « Mesure
      d'audience ») n'utilise ni cookie ni stockage local.
    </p>
    <p>
      Loomkeep n'utilise pas, à sa connaissance, de traceurs publicitaires
      destinés à établir un profil publicitaire des utilisateurs.
    </p>
    <h2>10. Données provenant des services de catalogue</h2>
    <p>
      Les données relatives aux œuvres affichées dans Loomkeep peuvent provenir
      de services tiers.
    </p>
    <p>
      Ces données ne constituent pas nécessairement des données personnelles de
      l'utilisateur.
    </p>
    <p>
      Lorsqu'une recherche est effectuée, Loomkeep transmet au fournisseur
      concerné les informations nécessaires à la recherche de l'œuvre demandée.
    </p>
    <p>
      Loomkeep ne transmet pas volontairement à ces fournisseurs l'adresse
      e-mail, le mot de passe ou les informations privées du compte dans le
      cadre d'une recherche de catalogue.
    </p>
