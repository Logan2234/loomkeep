    <h2>2. Principes appliqués</h2>
    <p>Loomkeep s'efforce de respecter les principes du RGPD, notamment :</p>
    <ul>
      <li>
        ne collecter que les données nécessaires aux finalités poursuivies ;
      </li>
      <li>utiliser les données uniquement pour les finalités indiquées ;</li>
      <li>limiter la durée de conservation ;</li>
      <li>assurer la sécurité des données ;</li>
      <li>
        permettre l'exercice des droits prévus par la réglementation applicable.
      </li>
    </ul>
    <h2>3. Données collectées</h2>
    <p>Les données traitées dépendent des fonctionnalités utilisées.</p>
    <h3>Création et gestion du compte</h3>
    <p>Loomkeep peut traiter notamment :</p>
    <ul>
      <li>adresse e-mail ;</li>
      <li>nom d'utilisateur ;</li>
      <li>nom d'affichage ;</li>
      <li>mot de passe ou dérivé cryptographique du mot de passe ;</li>
      <li>état de vérification de l'adresse e-mail ;</li>
      <li>langue ou préférences régionales ;</li>
      <li>préférences de notification.</li>
    </ul>
    <p>Le mot de passe n'est pas conservé en clair.</p>
    <h3>Profil</h3>
    <p>
      Lorsque l'utilisateur choisit de compléter son profil, Loomkeep peut
      traiter :
    </p>
    <ul>
      <li>nom d'utilisateur ;</li>
      <li>nom d'affichage ;</li>
      <li>biographie ;</li>
      <li>avatar ;</li>
      <li>paramètres de visibilité ;</li>
      <li>préférences liées au profil.</li>
    </ul>
    <p>
      Ces informations peuvent être visibles par d'autres utilisateurs lorsque
      l'utilisateur choisit un niveau de visibilité permettant leur partage.
    </p>
    <h3>Âge et contenu adulte</h3>
    <p>
      Loomkeep peut traiter une information relative à l'âge de l'utilisateur ou
      à son accès aux contenus adultes afin d'appliquer les restrictions prévues
      par le service.
    </p>
    <p>
      Il s'agit de la date de naissance complète : une simple information d'âge
      au moment de sa saisie deviendrait obsolète et ne permettrait plus de
      vérifier dans le temps que l'utilisateur reste éligible à ces contenus.
    </p>
    <h3>Données de suivi culturel</h3>
    <p>
      Lorsque l'utilisateur utilise Loomkeep pour suivre ses contenus, le
      service peut traiter notamment :
    </p>
    <ul>
      <li>œuvres présentes dans sa bibliothèque ;</li>
      <li>statut de suivi ;</li>
      <li>progression ;</li>
      <li>dates associées au suivi ;</li>
      <li>notes ;</li>
      <li>avis ;</li>
      <li>historique d'utilisation ;</li>
      <li>listes ;</li>
      <li>préférences de contenu.</li>
    </ul>
    <p>
      Ces informations peuvent révéler les centres d'intérêt et habitudes
      culturelles de l'utilisateur.
    </p>
    <h3>Fonctionnalités sociales</h3>
    <p>
      Lorsque l'utilisateur utilise les fonctionnalités sociales, Loomkeep peut
      traiter notamment :
    </p>
    <ul>
      <li>abonnements entre utilisateurs ;</li>
      <li>blocages ;</li>
      <li>avis ;</li>
      <li>commentaires ;</li>
      <li>réactions ;</li>
      <li>listes ;</li>
      <li>événements d'activité ;</li>
      <li>paramètres de visibilité ;</li>
      <li>signalements.</li>
    </ul>
    <p>
      La visibilité de certaines de ces informations dépend des fonctionnalités
      disponibles et des paramètres choisis par l'utilisateur.
    </p>
    <h3>Imports</h3>
    <p>
      Lorsque l'utilisateur utilise une fonctionnalité d'import, Loomkeep peut
      traiter les données contenues dans les fichiers ou données fournis par
      l'utilisateur afin de les intégrer à son compte.
    </p>
    <p>
      Les données importées deviennent ensuite soumises aux règles applicables
      aux données de suivi et de compte Loomkeep.
    </p>
    <h3>Données techniques et de sécurité</h3>
    <p>
      Pour assurer le fonctionnement et la sécurité du service, Loomkeep peut
      traiter certaines données techniques telles que :
    </p>
    <ul>
      <li>adresse IP ;</li>
      <li>informations relatives à la connexion ;</li>
      <li>événements de sécurité ;</li>
      <li>informations relatives à la session ;</li>
      <li>journaux techniques ;</li>
      <li>informations relatives aux erreurs ;</li>
      <li>informations nécessaires au diagnostic d'incidents.</li>
    </ul>
    <p>
      Les journaux techniques (accès, application) sont conservés par rotation
      de volume sur le serveur (environ 50 Mo par service, soit quelques jours à
      quelques semaines selon le trafic) ; lorsque le module de supervision est
      activé, ils sont en outre conservés 30 jours glissants dans l'outil de
      supervision (Loki). Les données d'erreur (stack traces) sont conservées
      dans l'outil de suivi des erreurs auto-hébergé (GlitchTip), selon sa durée
      de rétention par défaut.
    </p>
