    <p>
      Loomkeep étant un logiciel libre et auto-hébergeable, d'autres personnes
      peuvent exploiter leur propre instance. Dans ce cas, l'administrateur de
      l'instance concernée est responsable des traitements réalisés sur cette
      instance et doit fournir sa propre politique de confidentialité.
    </p>
